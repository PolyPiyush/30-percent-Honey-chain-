/**
 * Calculates geographic center and bounds of a batch's locations
 */
export const getBatchGeoCenter = (batch: TraceabilityBatch): { lat: number; lng: number } => {
  if (!batch.locations || batch.locations.length === 0) {
    return { lat: 18.5204, lng: 73.8567 };
  }
  let sumLat = 0;
  let sumLng = 0;
  batch.locations.forEach((l) => {
    sumLat += l.latitude;
    sumLng += l.longitude;
  });
  return {
    lat: sumLat / batch.locations.length,
    lng: sumLng / batch.locations.length,
  };
};
